/// Перевести строки в клетки. Сделано отдельной функцией, чтобы длина
/// каждой строки проверялась при сборке, а не оказалась короче на одну
/// клетку в одном значке из десяти.
fn toGrid(rows: [side][]const u8) [side][side]u8 {
    var out: [side][side]u8 = undefined;
    for (rows, 0..) |row, r| {
        if (row.len != side) @compileError("узор значка должен быть шириной ровно в side клеток");
        for (row, 0..) |cell, col| out[r][col] = cell;
    }
    return out;
}

// ---------------------------------------------------------------- тесты

const testing = std.testing;

test "умолчание — без значка, и оно нулевое" {
    try testing.expectEqual(@as(u8, 0), @intFromEnum(Icon.none));
    try testing.expectEqual(@as(usize, 0), Icon.none.weight());
}

test "каждый значок нарисован и не пустой" {
    for (all) |icon| {
        try testing.expect(icon.weight() > 0);
        try testing.expect(icon.label().len > 0);
        // И не залит целиком: сплошной квадрат — это не значок.
        try testing.expect(icon.weight() < side * side);
    }
}

test "ни один значок не повторяет другой" {
    // Два одинаковых значка — это два названия одного и того же, и выбор
    // между ними ничего не значит. Сравниваем узоры, а не имена.
    for (all, 0..) |a, i| {
        for (all[0..i]) |b| {
            try testing.expect(!std.meta.eql(a.pattern().*, b.pattern().*));
        }
    }
}

test "значки различимы не только целиком, но и по числу клеток" {
    // Совсем близкие по весу значки — повод посмотреть на них глазами.
    // Проверка не строгая: она ловит случай, когда значок скопировали
    // и поправили одну клетку.
    for (all, 0..) |a, i| {
        for (all[0..i]) |b| {
            var same: usize = 0;
            for (0..side) |r| {
                for (0..side) |col| {
                    if (a.on(r, col) == b.on(r, col)) same += 1;
                }
            }
            // Больше девяноста пяти процентов совпадения — это один и тот же
            // значок с правкой в пару клеток.
            try testing.expect(same * 100 / (side * side) < 95);
        }
    }
}

test "клетки за краем считаются пустыми, а не падают" {
    try testing.expect(!Icon.star.on(side, 0));
    try testing.expect(!Icon.star.on(0, side));
    try testing.expect(!Icon.star.on(1000, 1000));
}

test "полоски складываются в тот же узор, что и клетки" {
    // Окно рисует значок полосками; если счёт полосок разойдётся с узором,
    // значок нарисуется не тем, чем задуман.
    for (all) |icon| {
        for (0..side) |row| {
            var col: usize = 0;
            while (col < side) {
                const run = runLength(icon, row, col);
                if (run == 0) {
                    try testing.expect(!icon.on(row, col));
                    col += 1;
                    continue;
                }
                // Вся полоска закрашена…
                for (col..col + run) |x| try testing.expect(icon.on(row, x));
                // …а сразу за ней — пусто.
                try testing.expect(!icon.on(row, col + run));
                col += run + 1;
            }
        }
    }
}

test "у «без значка» нет ни одной закрашенной клетки" {
    for (0..side) |r| {
        for (0..side) |col| try testing.expect(!Icon.none.on(r, col));
    }
}

test "все значки перечислены в списке выбора" {
    // Значок, которого нет в списке, поставить нечем: он есть в модели,
    // виден в файле проекта и недостижим из окна.
    const fields = @typeInfo(Icon).@"enum".fields;
    // Все, кроме «без значка».
    try testing.expectEqual(fields.len - 1, all.len);
    inline for (fields) |f| {
        const icon: Icon = @enumFromInt(f.value);
        if (icon != .none) {
            var found = false;
            for (all) |it| {
                if (it == icon) found = true;
            }
            try testing.expect(found);
        }
    }
}
