//! Значки для объектов: метки, дорожки, клипа.
//!
//! Задача #81. Цвет отличает метки с одного взгляда, но цветов восемь,
//! и они кончаются. Значок говорит не «какая это метка», а «что с ней
//! делать»: ножницы — вырезать, микрофон — переозвучить, глаз —
//! посмотреть, восклицание — важно.
//!
//! **Значки рисуем сами, а не берём из шрифта.** Это правило уже оплачено
//! дважды: на кнопках пульта системный шрифт не знал ⏸ и ▶ и рисовал
//! пустой квадратик, а на кнопке выбора окна пришлось рисовать рамку окна
//! руками.
//!
//! **Значок — это узор из клеток, выписанный прямо здесь.** Не список
//! отрезков и не вызовы рисования: узор можно прочитать глазами в исходнике,
//! сравнить один значок с другим числом и проверить тестом, что ни один
//! не повторяет соседа и ни один не пустой. Окну остаётся закрасить клетки.
const std = @import("std");

/// Сторона значка в клетках. Двенадцать: меньше — не разглядеть ножницы,
/// больше — значок перестаёт помещаться в строку списка.
pub const side = 12;

/// Какой значок у объекта.
///
/// Ноль — без значка, и это не случайно: умолчание модели проекта обязано
/// быть нулевым, иначе восемьсот килобайт лягут в .exe готовыми байтами.
pub const Icon = enum(u8) {
    none = 0,
    scissors,
    mic,
    eye,
    bang,
    question,
    star,
    check,
    cross,
    lock,
    flag,

    pub fn label(self: Icon) []const u8 {
        return switch (self) {
            .none => "без значка",
            .scissors => "вырезать",
            .mic => "переозвучить",
            .eye => "посмотреть",
            .bang => "важно",
            .question => "разобраться",
            .star => "хорошее место",
            .check => "сделано",
            .cross => "выбросить",
            .lock => "не трогать",
            .flag => "начало куска",
        };
    }

    /// Узор значка: двенадцать строк по двенадцать клеток.
    /// Решётка — закрашенная клетка, точка — пустая.
    pub fn pattern(self: Icon) *const [side][side]u8 {
        return switch (self) {
            .none => &empty,
            .scissors => &scissors,
            .mic => &mic,
            .eye => &eye,
            .bang => &bang,
            .question => &question,
            .star => &star,
            .check => &check,
            .cross => &cross,
            .lock => &lock,
            .flag => &flag,
        };
    }

    /// Закрашена ли клетка.
    pub fn on(self: Icon, row: usize, col: usize) bool {
        if (row >= side or col >= side) return false;
        return self.pattern()[row][col] == '#';
    }

    /// Сколько клеток закрашено. Ноль — значка нет.
    pub fn weight(self: Icon) usize {
        var n: usize = 0;
        for (self.pattern()) |line| {
            for (line) |cell| {
                if (cell == '#') n += 1;
            }
        }
        return n;
    }
};

/// Все значки, кроме «без значка» — для меню выбора.
pub const all = [_]Icon{
    .scissors, .mic,   .eye,   .bang, .question,
    .star,     .check, .cross, .lock, .flag,
};

/// Сколько отрезков подряд закрашено в строке, начиная с `from`.
///
/// Окно рисует значок полосками, а не по клетке: двенадцать на двенадцать —
/// это сто сорок четыре вызова рисования на один значок, а полосок выходит
/// с десяток.
pub fn runLength(icon: Icon, row: usize, from: usize) usize {
    var n: usize = 0;
    var col = from;
    while (col < side and icon.on(row, col)) : (col += 1) n += 1;
    return n;
}

